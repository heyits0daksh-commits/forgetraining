"""
generate_batch21_missing_gym_staples.py — v5.36. Adds 19 common gym
exercises that an audit of the FORGE S&C Template Libraries against
exercises.json found were genuinely absent from the database (not a
matcher problem - see scripts/data_ops/dedupe_and_rematch_v5_35.py for
that half of the audit). Every one of these is referenced by name in one
or more of the ten sport template libraries (data/sc_templates/*.json)
dozens to hundreds of times, so until now those template slots fell
through to an unverified, equipment/injury-unchecked passthrough with no
real exercise data behind them at all.

WHY THESE 19, AND NOT THE OTHER ~150 STILL-UNMATCHED TEMPLATE NAMES:
these are ordinary, static-equipment strength-training exercises with a
close, well-established sibling already in the database to model from.
The rest of the unmatched list is either genuine sport-specific
conditioning/skill work with no strength-training equivalent to model
from at all (swim drills, sled sprint/pull/push by distance, running
zone/interval work, hangboard and campus-board climbing drills,
shadowboxing/bag rounds - these belong in a conditioning_guidance
structure, not exercises.json, by the same design logic already visible
in this file), or a colloquial name close enough to an EXISTING exercise
that a matcher alias was the right fix instead of a new entry (see the
_NAME_ALIASES change in backend/services/sc_template_library.py in the
same commit as this file - Barbell Row -> Barbell Bent-Over Row, Seated
Cable Row -> Cable Row, Kettlebell Swing -> Russian Kettlebell Swing,
etc.). Adding a new exercise for either of those would either invent
data no real exercise needs, or create a near-duplicate of something
that already exists.

HOW EACH ENTRY WAS BUILT: every one of primary/secondary/stabilizer
muscles, joint_stress, injuries_to_avoid, strength_requirements, and
sport_priority below is copied byte-for-byte from the single closest
sibling already in exercises.json (named in each entry's comment) -
never invented from scratch. Only name/id/category/movement_pattern/
difficulty/equipment/equipment_level differ from that sibling, because
those are exactly the fields that differ in real life between (say) a
"Barbell Shrug" and the "Trap Bar Shrug" it's modeled on. Six of the 19
introduce a new, more accurate equipment string than any existing entry
had (Calf Raise Machine, Ab Crunch Machine, Preacher Curl Machine,
Triceps Dip Machine, Hip Thrust Machine, Assisted Pull-up Machine) -
each added to EQUIPMENT_CATEGORIES's "Machines" group in
exercise_metadata.py in the same commit, at an equipment_level chosen to
sit in the same 13-45 band every other named machine in this file
already occupies, so build_equipment_catalog() and the equipment gate
treat them like any other named machine rather than falling back to
"Other".

Every other field (movement_plane, force_type, stability/balance/
coordination/mobility requirements, technical_complexity, fatigue_cost,
athletic_qualities, is_compound/push_pull/upper_lower/chain_emphasis,
tendons_loaded/ligaments_stressed/muscle_action_by_phase/
biomechanics_notes) is generated by the same enrich_exercise() /
derive_taxonomy_groups() / derive_connective_tissue() pipeline every
other exercise in the database already goes through - see
enrich_batch21_only.py, the companion enrichment script, and
enrich_batch16-20_only.py for the established two-step pattern this
follows.

Run: python scripts/generators/generate_batch21_missing_gym_staples.py
Then: python scripts/enrichment/enrich_batch21_only.py
"""
