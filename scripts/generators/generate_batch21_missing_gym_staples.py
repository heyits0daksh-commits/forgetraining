def main():
    with open(SRC, "r", encoding="utf-8") as f:
        data = json.load(f)

    existing_ids = {e["id"] for e in data["exercises"]}
    existing_names = {e["name"] for e in data["exercises"]}
    collide_ids = existing_ids & {e["id"] for e in NEW}
    collide_names = existing_names & {e["name"] for e in NEW}
    if collide_ids or collide_names:
        raise SystemExit(f"Collision, aborting: ids={collide_ids} names={collide_names}")

    BACKUP_DIR.mkdir(parents=True, exist_ok=True)
    shutil.copy(SRC, BACKUP)

    data["exercises"].extend(NEW)

    with open(SRC, "w", encoding="utf-8") as f:
        json.dump(data, f, indent=2, ensure_ascii=False)

    print(f"Added {len(NEW)} exercises. Backup at {BACKUP}. "
          f"Now run scripts/enrichment/enrich_batch21_only.py")


if __name__ == "__main__":
    main()
